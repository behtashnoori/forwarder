export type TranslationKey = keyof typeof translations.fa;

type I18nContextValue = {
  language: Language;
  direction: Direction;
  locale: string;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: TranslationKey) => string;
  tf: (key: TranslationKey, values: Record<string, string | number>) => string;
  statusLabel: (status: string) => string;
  shippingTypeLabel: (shippingType: string, options?: { full?: boolean }) => string;
  stepLabel: (step: string) => string;
  actionLabel: (action: string) => string;
  transportLabel: (method: string) => string;
};

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

const getInitialLanguage = (): Language => {
  if (typeof window === "undefined") return "fa";
  return window.localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "fa";
};

export const I18nProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage);
  const direction: Direction = language === "fa" ? "rtl" : "ltr";
  const locale = language === "fa" ? "fa-IR" : "en-US";

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = direction;
    window.localStorage.setItem(STORAGE_KEY, language);
  }, [direction, language]);

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      direction,
      locale,
      setLanguage: setLanguageState,
      toggleLanguage: () => setLanguageState((current) => (current === "fa" ? "en" : "fa")),
      t: (key) => translations[language][key],
      tf: (key, values) =>
        Object.entries(values).reduce(
          (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
          translations[language][key],
        ),
      statusLabel: (status) => translations[language][`status.${status}` as TranslationKey] ?? status,
      shippingTypeLabel: (shippingType, options) => {
        const suffix = options?.full ? "Full" : "";
        return translations[language][`shipping.type.${shippingType}${suffix}` as TranslationKey] ?? shippingType;
      },
      stepLabel: (step) => translations[language][`step.${step}` as TranslationKey] ?? step,
      actionLabel: (action) => translations[language][`action.${action}` as TranslationKey] ?? action,
      transportLabel: (method) => translations[language][`transport.${method}` as TranslationKey] ?? method,
    }),
    [direction, language, locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return context;
};
